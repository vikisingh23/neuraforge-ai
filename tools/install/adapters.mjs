/**
 * Per-tool adapters. The repo keeps ONE source of truth (agents/<name>.md + agents/<name>.json,
 * skills/, rules/, AGENTS.md). These pure functions turn it into each tool's native format.
 *
 * Native formats (checked against vendor docs, Nov 2026):
 *   Claude Code  .claude/agents/<name>.md   markdown + YAML frontmatter (name, description required). Files without it are skipped.
 *   Gemini CLI   .gemini/agents/<name>.md   markdown + YAML frontmatter (name, description; kind: local)
 *   Codex        .codex/agents/<name>.toml  name, description, developer_instructions (required)
 *   Skills       .claude/skills, .kiro/skills, and the shared .agents/skills (Gemini CLI, Antigravity, Codex)
 */

// Orchestrators spawn other agents. Subagents cannot spawn subagents in Claude Code or Gemini CLI,
// so these run in the main thread through their skill instead of being registered as subagents.
export const MAIN_THREAD_ONLY = new Set(['feature-pipeline', 'fullstack-orchestrator']);

const CLAUDE_TOOL_MAP = {
  read: ['Read'],
  write: ['Write', 'Edit'],
  shell: ['Bash'],
  grep: ['Grep'],
  glob: ['Glob'],
  web: ['WebFetch', 'WebSearch'],
  web_fetch: ['WebFetch'],
  web_search: ['WebSearch'],
  // 'code' (Kiro code intelligence) and 'subagent' have no Claude subagent equivalent
};

const oneLine = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const yamlString = (s) => JSON.stringify(oneLine(s)); // JSON strings are valid YAML double-quoted scalars

export function claudeTools(tools = []) {
  const out = [];
  for (const t of tools) {
    if (t.startsWith('@')) out.push(`mcp__${t.slice(1).replace('/', '__')}`);
    else for (const m of CLAUDE_TOOL_MAP[t] || []) if (!out.includes(m)) out.push(m);
  }
  return out;
}

function claudeModel(model) {
  if (/sonnet/i.test(model || '')) return 'sonnet';
  if (/haiku/i.test(model || '')) return 'haiku';
  if (/opus/i.test(model || '')) return 'opus';
  return undefined;
}

/** Claude Code subagent file. Body is the full agent prompt, so the subagent is self-contained. */
export function toClaudeAgent(name, cfg, md) {
  const tools = claudeTools(cfg.tools);
  const model = claudeModel(cfg.model);
  const fm = ['---', `name: ${name}`, `description: ${yamlString(cfg.description || name)}`];
  if (tools.length) fm.push(`tools: ${tools.join(', ')}`);
  if (model) fm.push(`model: ${model}`);
  fm.push('---', '');
  return fm.join('\n') + md.replace(/^\uFEFF/, '').trimStart() + (md.endsWith('\n') ? '' : '\n');
}

/** Gemini CLI custom subagent. Tool names differ per CLI version, so tools are left unset (inherit). */
export function toGeminiAgent(name, cfg, md) {
  const slug = name.toLowerCase().replace(/[^a-z0-9_-]/g, '-');
  const fm = ['---', `name: ${slug}`, `description: ${yamlString(cfg.description || name)}`, 'kind: local', '---', ''];
  return fm.join('\n') + md.replace(/^\uFEFF/, '').trimStart() + (md.endsWith('\n') ? '' : '\n');
}

const tomlBasic = (s) => JSON.stringify(String(s)); // valid TOML basic string

/** Codex custom agent. Sandbox, approvals and MCP are inherited from the parent session (Codex ignores them here). */
export function toCodexAgentToml(name, cfg, md) {
  const id = name.replace(/-/g, '_');
  const body = md.replace(/^\uFEFF/, '').trim();
  const instructions = body.includes("'''")
    ? tomlBasic(body) // single-line escaped form when the literal delimiter appears in the text
    : `'''\n${body}\n'''`;
  return [
    `name = ${tomlBasic(id)}`,
    `description = ${tomlBasic(oneLine(cfg.description || name))}`,
    `developer_instructions = ${instructions}`,
    '',
  ].join('\n');
}

/** Codex reads MCP servers from config.toml. Environment values are never written; required names are listed in a comment. */
export function mcpToCodexToml(mcp) {
  const lines = ['# Generated by NeuraForge from .mcp.json. Set required environment variables in your shell.', ''];
  for (const [name, s] of Object.entries(mcp.mcpServers || {})) {
    const key = /^[A-Za-z0-9_-]+$/.test(name) ? name : tomlBasic(name);
    lines.push(`[mcp_servers.${key}]`);
    if (s.command) {
      lines.push(`command = ${tomlBasic(s.command)}`);
      if (s.args?.length) lines.push(`args = [${s.args.map(tomlBasic).join(', ')}]`);
    } else if (s.url) {
      lines.push(`url = ${tomlBasic(s.url)}`);
    } else continue;
    const envNames = Object.keys(s.env || {});
    if (envNames.length) lines.push(`# requires env: ${envNames.join(', ')}`);
    lines.push('');
  }
  return lines.join('\n');
}
